export interface ProxySpreadRow {
  ratingBucket: string;
  representativeIssuer: string;
  fredSeriesId: string;
  asOfDate: string;
  tenorsBp: number[]; // [1Y, 3Y, 5Y, 7Y, 10Y]
  provenanceStatus: string;
  sourceUrl: string;
}

/**
 * Parses data/raw/proxy_spreads.csv generated by scripts/fetch_proxy_spreads.py
 * to build the rating-to-spread map and term structure (Section 4.1).
 */
function parseProxySpreadsCsv(csvText: string): Record<string, ProxySpreadRow> {
  const map: Record<string, ProxySpreadRow> = {};
  const lines = csvText
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l.length > 0 && !l.startsWith('#'));

  if (lines.length < 2) return map;

  for (let i = 1; i < lines.length; i++) {
    // Parse CSV line respecting quoted strings
    const cols: string[] = [];
    let current = '';
    let inQuotes = false;
    for (let c = 0; c < lines[i].length; c++) {
      const ch = lines[i][c];
      if (ch === '"') {
        inQuotes = !inQuotes;
      } else if (ch === ',' && !inQuotes) {
        cols.push(current.trim());
        current = '';
      } else {
        current += ch;
      }
    }
    cols.push(current.trim());

    if (cols.length >= 11) {
      const ratingBucket = cols[0];
      const representativeIssuer = cols[1];
      const fredSeriesId = cols[2];
      const asOfDate = cols[3];
      const tenorsBp = [
        Number(cols[4]),
        Number(cols[5]),
        Number(cols[6]),
        Number(cols[7]),
        Number(cols[8]),
      ];
      const provenanceStatus = cols[9];
      const sourceUrl = cols[10];
      const row: ProxySpreadRow = {
        ratingBucket,
        representativeIssuer,
        fredSeriesId,
        asOfDate,
        tenorsBp,
        provenanceStatus,
        sourceUrl,
      };
      map[representativeIssuer] = row;
      map[ratingBucket] = row;
    }
  }
  return map;
}

export const PROXY_SPREAD_TABLE: Record<string, ProxySpreadRow> =
  parseProxySpreadsCsv(proxySpreadsCsvRaw);

function getSpreadTermStructure(ticker: string, fallback: number[]): number[] {
  const row = PROXY_SPREAD_TABLE[ticker];
  if (row && row.tenorsBp.length === 5 && row.tenorsBp.every((n) => Number.isFinite(n))) {
    return [...row.tenorsBp];
  }
  return fallback;
}

